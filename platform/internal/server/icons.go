// icon returns an inline SVG element for the named icon. An optional extra CSS
// class can be supplied. Unknown names render nothing (no broken glyph).
func icon(name string, class ...string) template.HTML {
	body, ok := iconPaths[name]
	if !ok {
		return ""
	}
	cls := "ic"
	if len(class) > 0 && class[0] != "" {
		cls += " " + class[0]
	}
	var b strings.Builder
	b.WriteString(`<svg class="`)
	b.WriteString(cls)
	b.WriteString(`" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">`)
	b.WriteString(body)
	b.WriteString(`</svg>`)
	return template.HTML(b.String())
}
